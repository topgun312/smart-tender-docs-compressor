TENDER_SYSTEM_PROMPT = """Ты — аналитик государственных закупок (zakupki.gov.ru). \
Ты читаешь текст конкурсной документации и выделяешь из него ключевые условия контракта. \
Отвечай строго на русском языке."""

TENDER_USER_PROMPT = """Прочитай текст конкурсной документации и составь краткую выжимку.

Верни ответ СТРОГО в формате JSON без пояснений, без Markdown-разметки и без лишнего текста.
Схема ответа:
{{
  "contract_amount": "сумма контракта (число или 'не указано')",
  "contract_date": "дата заключения контракта в формате ДД.ММ.ГГГГ (или 'не указано')",
  "contract_start_date": "дата начала исполнения контракта в формате ДД.ММ.ГГГГ (или 'не указано')",
  "contract_end_date": "дата окончания исполнения контракта в формате ДД.ММ.ГГГГ (или 'не указано')",
  "deadlines": "сроки выполнения работ (или 'не указано')",
  "contractor_requirements": ["ключевое требование 1", "ключевое требование 2", ...],
  "fines": ["штраф/неустойка 1", "штраф/неустойка 2", ...],
  "security_amount": "размер обеспечения исполнения контракта (число или 'не указано')",
  "security_type": "способ обеспечения контракта: банковская гарантия, внесение денежных средств,
  поручительство и т.п. (или 'не указано')",
  "security_conditions": ["условие по обеспечению контракта 1", "условие по обеспечению контракта 2", ...]
}}

Правила заполнения:
- contract_date, contract_start_date, contract_end_date и deadlines — это разные даты, не путай их.
  contract_date — когда контракт заключён, contract_start_date — когда начали исполнять,
  contract_end_date — крайний срок окончания исполнения, deadlines — общий срок выполнения работ.
- В security_conditions указывай все условия, связанные с обеспечением контракта: срок возврата
  обеспечения, требования к банковской гарантии (срок действия, независимость), случаи удержания
  обеспечения, право на замену способа обеспечения и т.п.
- Если какой-то раздел в документе отсутствует, используй значение "не указано" \
(для строковых полей) или пустой список (для contractor_requirements, fines и security_conditions).

Текст документа:
---
{document_text}
---
"""


def build_tender_messages(document_text: str) -> list[dict]:
    """Собрать сообщения чата для суммаризации тендера."""
    return [
        {
            "role": "user",
            "content": TENDER_USER_PROMPT.format(document_text=document_text),
        },
    ]
